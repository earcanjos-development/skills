#!/usr/bin/env python3
"""Shared-methods registry: render the pack rules, scan for offenders, check a diff.

    compound-packs/shared-methods/registry.json   (source of truth)
        -> compound-packs/shared-methods/<concept>.md   (generated CE pack rules)

    render --write | --check   write the rule files, or exit 1 when they drifted
    scan                       every pattern hit outside its owner, allowlisted or not
    check [--base REF]         rules a diff touches, and new offenders it adds

Stdlib only, so a project can vendor it as scripts/shared_methods.py and
run it from git hooks or tests on a bare python3. Project root:
SHARED_METHODS_ROOT, else `git rev-parse --show-toplevel`. Pack folder:
SHARED_METHODS_PACK (default compound-packs/shared-methods).
Source: earcanjos-development/skills, skill refactor-update-shared-methods.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

def _project_root() -> Path:
    """SHARED_METHODS_ROOT, else the git top level of the current directory,
    else the parent of this script's folder (a copy vendored into scripts/)."""
    env = os.environ.get("SHARED_METHODS_ROOT")
    if env:
        return Path(env).resolve()
    try:
        top = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True,
                             text=True, check=True).stdout.strip()
        if top:
            return Path(top)
    except (OSError, subprocess.CalledProcessError):
        pass
    return Path(__file__).resolve().parents[1]


ROOT = _project_root()
PACK = ROOT / os.environ.get("SHARED_METHODS_PACK", "compound-packs/shared-methods")
REGISTRY = PACK / "registry.json"
SCHEMA = "shared-methods@1"
FIX = "run `python3 scripts/shared_methods.py render --write` and commit the pack"
GENERATED = "<!-- generated from registry.json by scripts/shared_methods.py; edit the registry -->"


def load_registry(path: Path = REGISTRY) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("schema") != SCHEMA:
        raise ValueError(f"{path}: schema is {data.get('schema')!r}, expected {SCHEMA!r}")
    return data


def _yaml_str(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def render_rule(rule: dict) -> str:
    """One CE pack rule: frontmatter (title, applies_when, tags) + body."""
    lines = ["---", f"title: {_yaml_str(rule['title'])}", "applies_when:"]
    lines += [f"  - {_yaml_str(item)}" for item in rule["applies_when"]]
    lines.append("tags: [" + ", ".join(rule.get("tags", [])) + "]")
    lines += ["---", "", GENERATED, "", rule["body"], "", f"Owner: `{rule['owner']}`.", ""]
    for stack in sorted(rule["use"]):
        lines.append(f"Use ({stack}):")
        lines += [f"- `{name.split(' ', 1)[0]}`" + (f" {name.split(' ', 1)[1]}" if " " in name else "")
                  for name in rule["use"][stack]]
        wraps = rule.get("wraps", {}).get(stack, [])
        if wraps:
            lines.append(f"- wraps: {', '.join(f'`{w}`' for w in wraps)}")
        patterns = rule.get("instead_of", {}).get(stack, [])
        if patterns:
            lines.append("- not written outside the owner (regex): "
                         + ", ".join(f"`{p}`" for p in patterns))
        lines.append("")
    allow = rule.get("allowlist", {})
    if allow:
        lines.append("Known offenders (allowlist; may only shrink):")
        lines += [f"- `{path}`: {why}" for path, why in sorted(allow.items())]
        lines.append("")
    return "\n".join(lines)


def rendered(registry: dict) -> dict[str, str]:
    return {f"{rule['concept']}.md": render_rule(rule) for rule in registry["rules"]}


def drift(registry: dict, pack: Path = PACK) -> list[str]:
    """Rule files missing, stale, or generated by an older registry."""
    want = rendered(registry)
    problems = [f"{name}: missing or stale" for name, text in want.items()
                if not (pack / name).is_file() or (pack / name).read_text(encoding="utf-8") != text]
    for path in sorted(pack.glob("*.md")):
        if path.name not in want and GENERATED in path.read_text(encoding="utf-8"):
            problems.append(f"{path.name}: generated rule no longer in the registry")
    return problems


def write(registry: dict, pack: Path = PACK) -> list[str]:
    written = []
    for name, text in rendered(registry).items():
        target = pack / name
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8")
            written.append(name)
    return written


def _dotted(data: dict, key: str):
    for part in key.split("."):
        data = data[part]
    return data


def scan_files(registry: dict, stack: str, root: Path = ROOT) -> list[Path]:
    spec = registry["scan"][stack]
    paths = _dotted(json.loads((root / spec["paths_from"]).read_text(encoding="utf-8")),
                    spec["paths_key"])
    found = []
    for entry in paths:
        base = root / entry
        if base.is_file():
            found.append(base)
        elif base.is_dir():
            found += [p for p in sorted(base.rglob("*"))
                      if p.is_file() and p.suffix in spec["suffixes"]]
    return found


def hits(registry: dict, root: Path = ROOT) -> dict[str, dict[str, list[str]]]:
    """concept -> repo-relative file -> matching lines, owner excluded."""
    result: dict[str, dict[str, list[str]]] = {}
    for rule in registry["rules"]:
        per_file = result.setdefault(rule["concept"], {})
        for stack, patterns in rule.get("instead_of", {}).items():
            compiled = [re.compile(p) for p in patterns]
            for path in scan_files(registry, stack, root):
                rel = path.relative_to(root).as_posix()
                if rel == rule["owner"]:
                    continue
                text = path.read_text(encoding="utf-8", errors="replace")
                for lineno, line in enumerate(text.splitlines(), start=1):
                    if any(c.search(line) for c in compiled):
                        per_file.setdefault(rel, []).append(f"{rel}:{lineno}: {line.strip()}")
    return result


def violations(registry: dict, root: Path = ROOT) -> tuple[list[str], list[str]]:
    """(new offenders outside the allowlist, allowlist entries that no longer match)."""
    found = hits(registry, root)
    new, stale = [], []
    for rule in registry["rules"]:
        allow = rule.get("allowlist", {})
        per_file = found.get(rule["concept"], {})
        new += [f"[{rule['concept']}] {line}"
                for rel, lines in per_file.items() if rel not in allow for line in lines]
        stale += [f"[{rule['concept']}] {rel}: allowlisted but no longer matches; remove it"
                  for rel in allow if rel not in per_file]
    return new, stale


def _diff(base: str, root: Path = ROOT) -> str:
    return subprocess.run(["git", "diff", "-U0", "--no-color", base], cwd=root,
                          capture_output=True, text=True, check=True).stdout


def parse_diff(text: str) -> dict[str, dict[str, list[str]]]:
    """file -> {'+': added lines, '-': removed lines}."""
    files: dict[str, dict[str, list[str]]] = {}
    current = None
    for line in text.splitlines():
        if line.startswith("diff --git "):
            current = None
        elif line.startswith(("+++ ", "--- ")):
            name = line[4:].strip()
            if name != "/dev/null":
                current = files.setdefault(name[2:] if name[1:2] == "/" else name,
                                           {"+": [], "-": []})
        elif current is not None and line[:1] in "+-":
            current[line[0]].append(line[1:])
    return files


def check_diff(registry: dict, diff: dict[str, dict[str, list[str]]]) -> tuple[dict, list[str]]:
    """(concept -> reasons it applies, new offenders the diff adds)."""
    applies: dict[str, list[str]] = {}
    offenders: list[str] = []
    for rule in registry["rules"]:
        compiled = [re.compile(p) for ps in rule.get("instead_of", {}).values() for p in ps]
        allow = rule.get("allowlist", {})
        for rel, sides in sorted(diff.items()):
            if rel == rule["owner"]:
                applies.setdefault(rule["concept"], []).append(f"touches owner {rel}")
                continue
            for sign, lines in sides.items():
                for line in lines:
                    if any(c.search(line) for c in compiled):
                        verb = "adds" if sign == "+" else "removes"
                        applies.setdefault(rule["concept"], []).append(
                            f"{rel} {verb}: {line.strip()}")
                        if sign == "+" and rel not in allow:
                            offenders.append(f"[{rule['concept']}] {rel}: {line.strip()} "
                                             f"(use {', '.join(n for ns in rule['use'].values() for n in ns)})")
    return applies, offenders


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("render", help="write or check the generated rule files")
    mode = r.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    sub.add_parser("scan", help="pattern hits outside each owner")
    c = sub.add_parser("check", help="rules a diff touches and offenders it adds")
    c.add_argument("--base", default="main", help="diff base: a ref or A..B range (default: main)")
    args = ap.parse_args(argv)
    registry = load_registry()

    if args.cmd == "render":
        if args.write:
            for name in write(registry):
                print(f"wrote {PACK.relative_to(ROOT) / name}")
            return 0
        problems = drift(registry)
        for p in problems:
            print(f"drift: {p}")
        if problems:
            print(FIX)
        return 1 if problems else 0

    if args.cmd == "scan":
        new, stale = violations(registry)
        for concept, per_file in hits(registry).items():
            allow = next(r for r in registry["rules"] if r["concept"] == concept).get("allowlist", {})
            for rel, lines in per_file.items():
                tag = "allowlisted" if rel in allow else "NEW"
                for line in lines:
                    print(f"[{concept}] {tag} {line}")
        for line in stale:
            print(f"stale {line}")
        print(f"{len(new)} new offender(s), {len(stale)} stale allowlist entr(ies)")
        return 1 if new or stale else 0

    applies, offenders = check_diff(registry, parse_diff(_diff(args.base)))
    titles = {r["concept"]: r["title"] for r in registry["rules"]}
    for concept, reasons in applies.items():
        print(f"rule {concept}: {titles[concept]}")
        for reason in reasons:
            print(f"  - {reason}")
    for line in offenders:
        print(f"new offender {line}")
    print(f"{len(applies)} rule(s) apply, {len(offenders)} new offender(s)")
    return 1 if offenders else 0


if __name__ == "__main__":
    sys.exit(main())
